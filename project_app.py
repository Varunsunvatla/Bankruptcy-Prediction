import streamlit as st
import joblib
import numpy as np
# Load model and scaler
model = joblib.load("/content/model.pkl")
st.set_page_config(page_title="Bankruptcy Prevention", page_icon="🏦")
st.title("🏦 Bankruptcy Prediction")
st.write("Enter the feature values below to predict the outcome.")
# User Inputs
industrial_risk = st.selectbox(
    "Industrial Risk", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low Risk', 'Medium Risk', 'High Risk'][[0, 0.5, 1].index(x)]}")
management_risk = st.selectbox(
    "Management Risk", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low Risk', 'Medium Risk', 'High Risk'][[0, 0.5, 1].index(x)]}")
financial_flexibility = st.selectbox(
    "Financial Flexibility", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low', 'Medium', 'High'][[0, 0.5, 1].index(x)]}")
credibility = st.selectbox(
    "Credibility", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low', 'Medium', 'High'][[0, 0.5, 1].index(x)]}")
competitiveness = st.selectbox(
    "Competitiveness", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low', 'Medium', 'High'][[0, 0.5, 1].index(x)]}")
operating_risk = st.selectbox(
    "Operating Risk", [0, 0.5, 1],
    format_func=lambda x: f"{x} - {['Low Risk', 'Medium Risk', 'High Risk'][[0, 0.5, 1].index(x)]}")
if st.button("Predict outcome"):
    input_data = np.array([[
        industrial_risk,
        management_risk,
        financial_flexibility,
        credibility,
        competitiveness,
        operating_risk
    ]])
    # Predict
    prediction = model.predict(input_data)
    # Display Result
    if prediction[0] == 1:
        st.error("🔴 Bankruptcy")
    else:
        st.success("🟢 Non-bankruptcy")

